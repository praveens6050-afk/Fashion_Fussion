'use strict';
const fs=require('fs');
const assert=require('assert');
const read=p=>fs.readFileSync(p,'utf8');
const login=read('admin-panel/crm-login.html');
const loginJs=read('admin-panel/crm-login.js');
const page=read('admin-panel/crm.html');
const auth=read('admin-panel/crm-auth.js');
const config=read('admin-panel/supabase-config.js');
const leads=read('admin-panel/admin-crm.js');
const followups=read('admin-panel/admin-crm-followups.js');
const migration=read('supabase/migrations/20261017110000_admin_seller_lead_crm.sql');
assert(login.includes('crm-login.js?v=20261017-crm-login'),'CRM login page must load its auth controller');
assert(loginJs.includes("select('is_admin')")&&loginJs.includes("data?.is_admin===true"),'CRM sign-in must verify admin role server-side');
assert(loginJs.includes("location.replace('crm.html')"),'Verified admins must be routed to CRM');
assert(page.includes('id="dashboard"')&&page.includes('data-admin-ready="false"'),'CRM page must remain hidden until authorization succeeds');
assert(auth.includes("select('is_admin')")&&auth.includes("profile?.is_admin!==true"),'CRM route must independently enforce admin access');
assert(auth.includes("location.replace('crm-login.html')"),'CRM must redirect on sign-out');
assert(config.includes("const isCrmPage=page==='crm.html'"),'CRM route must be detected explicitly');
assert(config.includes("add('admin-crm.js?v=20261017-crm'")&&config.includes("add('admin-crm-followups.js?v=20261017-crm-followups'"),'CRM modules must load on the CRM route');
assert(!/function loadCrmModules\(\)\s*\{[^}]*admin-orders\.js/s.test(config),'CRM route must not load admin order-management modules');
assert(leads.includes('async function importCsv')&&leads.includes('no existing lead was overwritten'),'CSV import must validate and avoid overwriting existing records');
assert(followups.includes('seller_lead_tasks')&&followups.includes('seller_lead_activities'),'Follow-up tasks and activity timeline must be wired');
assert(followups.includes('never sends messages'),'CRM must explicitly remain manual-only');
for(const marker of ['seller_lead_tasks_admin_select','seller_lead_tasks_admin_insert','seller_lead_activities_admin_select','seller_lead_activities_admin_insert'])assert(migration.includes(marker),'Missing admin-only RLS policy: '+marker);
assert(migration.includes('enable row level security'),'CRM activity/task tables must enable RLS');
console.log('CRM panel contract checks passed: standalone route, admin-only auth, isolated module loading, CSV safety, follow-ups, and RLS markers.');
