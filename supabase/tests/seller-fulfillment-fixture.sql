-- Minimal isolated PostgreSQL fixture for seller fulfilment transition tests.
CREATE SCHEMA IF NOT EXISTS auth;
DO $$ BEGIN
  CREATE ROLE anon NOLOGIN;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
  CREATE ROLE authenticated NOLOGIN;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
CREATE OR REPLACE FUNCTION auth.uid() RETURNS uuid
LANGUAGE sql STABLE AS $$
  SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;

CREATE TABLE public.orders (
  id bigint PRIMARY KEY,
  items jsonb NOT NULL DEFAULT '[]'::jsonb,
  fulfillment_status text NOT NULL DEFAULT 'ordered',
  CONSTRAINT orders_fulfillment_status_check CHECK (
    fulfillment_status = ANY (ARRAY['ordered'::text, 'packed'::text, 'shipped'::text, 'out_for_delivery'::text, 'delivered'::text, 'cancelled'::text])
  )
);
CREATE TABLE public.seller_profiles (
  user_id uuid PRIMARY KEY,
  status text NOT NULL
);
CREATE TABLE public.seller_product_submissions (
  seller_id uuid NOT NULL,
  approved_product_id bigint
);
CREATE TABLE public.order_shipments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL,
  awb_code text,
  status text
);
GRANT USAGE ON SCHEMA public, auth TO authenticated;
GRANT EXECUTE ON FUNCTION auth.uid() TO authenticated;

