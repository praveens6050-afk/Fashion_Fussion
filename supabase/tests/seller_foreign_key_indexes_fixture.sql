CREATE TABLE public.products (id bigint PRIMARY KEY);
CREATE TABLE public.seller_profiles (user_id uuid PRIMARY KEY);
CREATE TABLE public.seller_creator_offers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seller_id uuid NOT NULL REFERENCES public.seller_profiles(user_id),
  product_id bigint NOT NULL REFERENCES public.products(id),
  UNIQUE (seller_id, product_id)
);
CREATE TABLE public.seller_leads (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  converted_seller_id uuid REFERENCES public.seller_profiles(user_id),
  company_name text NOT NULL,
  source_marketplace text NOT NULL,
  UNIQUE (company_name, source_marketplace)
);
