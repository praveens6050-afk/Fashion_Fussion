-- Restore the foundational orders table required by the earliest customer-address
-- migration. This repository's migration history starts with ALTER TABLE orders,
-- but does not contain the original table-creation migration.
-- Keep this migration additive and safe when replayed against an existing schema.
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  razorpay_order_id text unique,
  razorpay_payment_id text unique,
  razorpay_signature text,
  total_amount numeric not null default 0 check (total_amount >= 0),
  currency text not null default 'INR',
  status text not null default 'creating',
  customer_name text,
  customer_email text,
  customer_phone text,
  items jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.orders enable row level security;
