-- Unified inbound CRM inbox. Branch-only; do not apply to production until safe replay and approval.
create table if not exists public.crm_inbox_conversations (
  id bigint generated by default as identity primary key,
  provider text not null check (provider in ('whatsapp','email')),
  provider_thread_id text,
  provider_message_id text not null,
  department text not null check (department in ('customer_support','seller_support','sales','marketing')),
  contact_type text not null default 'unknown' check (contact_type in ('customer','seller','prospect','unknown')),
  contact_user_id uuid references auth.users(id) on delete set null,
  contact_name text,
  contact_email text,
  contact_phone text,
  inbox_address text,
  subject text,
  latest_message text not null,
  received_at timestamptz not null default now(),
  status text not null default 'open' check (status in ('open','assigned','waiting','closed')),
  priority text not null default 'normal' check (priority in ('low','normal','high','urgent')),
  assigned_to uuid references auth.users(id) on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(provider,provider_message_id)
);
create index if not exists crm_inbox_dept_received_idx on public.crm_inbox_conversations(department,received_at desc);
create index if not exists crm_inbox_contact_email_idx on public.crm_inbox_conversations(lower(contact_email));
create index if not exists crm_inbox_contact_phone_idx on public.crm_inbox_conversations(contact_phone);
create table if not exists public.crm_inbox_messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.crm_inbox_conversations(id) on delete cascade,
  provider_message_id text not null,
  direction text not null check (direction in ('inbound','outbound')),
  sender_label text,
  body text not null,
  received_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  unique(provider_message_id,direction)
);
create index if not exists crm_inbox_messages_conversation_idx on public.crm_inbox_messages(conversation_id,received_at);
alter table public.crm_inbox_conversations enable row level security;
alter table public.crm_inbox_messages enable row level security;
revoke all on public.crm_inbox_conversations,public.crm_inbox_messages from anon,authenticated;
grant select,update on public.crm_inbox_conversations to authenticated;
grant select on public.crm_inbox_messages to authenticated;
create or replace function public.crm_inbox_can_access(p_department text)
returns boolean language sql stable security definer set search_path=pg_catalog,public,auth
as $$
 select exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.is_admin is true)
 or exists(select 1 from public.crm_team_members m where m.user_id=(select auth.uid()) and m.is_active is true and m.role=p_department)
$$;
revoke all on function public.crm_inbox_can_access(text) from public,anon;
grant execute on function public.crm_inbox_can_access(text) to authenticated;
drop policy if exists crm_inbox_conversations_department_read on public.crm_inbox_conversations;
create policy crm_inbox_conversations_department_read on public.crm_inbox_conversations for select to authenticated using (public.crm_inbox_can_access(department));
drop policy if exists crm_inbox_conversations_department_update on public.crm_inbox_conversations;
create policy crm_inbox_conversations_department_update on public.crm_inbox_conversations for update to authenticated using (public.crm_inbox_can_access(department)) with check (public.crm_inbox_can_access(department));
drop policy if exists crm_inbox_messages_department_read on public.crm_inbox_messages;
create policy crm_inbox_messages_department_read on public.crm_inbox_messages for select to authenticated using (exists(select 1 from public.crm_inbox_conversations c where c.id=conversation_id and public.crm_inbox_can_access(c.department)));
comment on table public.crm_inbox_conversations is 'Inbound WhatsApp and email messages routed to a CRM department. Provider webhooks write using service role; team users can read only their department.';
