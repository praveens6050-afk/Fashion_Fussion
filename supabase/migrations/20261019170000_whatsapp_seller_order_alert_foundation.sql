-- Seller transactional order-alert outbox and staging only.
-- No provider dispatch, no automatic retry, no historical-order backfill.
CREATE TABLE IF NOT EXISTS public.whatsapp_seller_order_notification_outbox (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE RESTRICT,
 seller_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
 event_type text NOT NULL DEFAULT 'seller_order_received' CHECK (event_type='seller_order_received'),
 status text NOT NULL DEFAULT 'pending_review' CHECK (status IN ('pending_review','ready','sending','accepted','delivered','read','failed','blocked')),
 attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count BETWEEN 0 AND 1),
 template_name text NOT NULL DEFAULT 'seller_order_received' CHECK (template_name='seller_order_received'),
 provider_message_id text CHECK (provider_message_id IS NULL OR (length(provider_message_id)<=255 AND provider_message_id ~ '^wamid[.][^[:space:]]+$')),
 last_error_code text CHECK (last_error_code IS NULL OR last_error_code ~ '^[A-Z0-9_:-]{1,64}$'),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 attempt_started_at timestamptz,
 provider_sent_at timestamptz,
 provider_delivered_at timestamptz,
 provider_failed_at timestamptz,
 UNIQUE(order_id,seller_id,event_type)
);
CREATE INDEX IF NOT EXISTS whatsapp_seller_order_outbox_recent_idx
 ON public.whatsapp_seller_order_notification_outbox(created_at DESC,status);
ALTER TABLE public.whatsapp_seller_order_notification_outbox ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.whatsapp_seller_order_notification_outbox FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE public.whatsapp_seller_order_notification_outbox TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.whatsapp_seller_order_notification_outbox_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.stage_whatsapp_seller_order_alert(
 p_order_id bigint,
 p_activation_cutoff timestamptz
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
 v_order public.orders%rowtype;
 v_inserted integer;
BEGIN
 IF p_order_id IS NULL OR p_order_id<=0 OR p_activation_cutoff IS NULL
    OR p_activation_cutoff>now() OR p_activation_cutoff<'2026-10-01'::timestamptz
 THEN RETURN 0; END IF;

 SELECT * INTO v_order FROM public.orders o
 WHERE o.id=p_order_id
   AND o.created_at >= greatest(p_activation_cutoff,now()-interval '24 hours')
   AND o.created_at <= now()
   AND o.fulfillment_status='ordered'
   AND ((o.payment_method='prepaid' AND o.status='paid' AND o.payment_verified_at IS NOT NULL)
     OR (o.payment_method='cod' AND o.status IN ('cod_pending','cod_collected')));
 IF NOT FOUND OR v_order.items IS NULL OR pg_catalog.jsonb_typeof(v_order.items)<>'array'
 THEN RETURN 0; END IF;

 INSERT INTO public.whatsapp_seller_order_notification_outbox
   (order_id,seller_id,event_type,status,template_name)
 SELECT DISTINCT v_order.id,sps.seller_id,'seller_order_received','pending_review','seller_order_received'
 FROM pg_catalog.jsonb_array_elements(v_order.items) item
 LEFT JOIN public.product_variants pv
   ON pv.id=CASE WHEN item->>'variant_id' ~ '^[0-9]+$'
     THEN (item->>'variant_id')::bigint ELSE NULL END
 JOIN public.seller_product_submissions sps
   ON sps.approved_product_id=COALESCE(
     CASE WHEN item->>'id' ~ '^[0-9]+$' THEN (item->>'id')::bigint ELSE NULL END,
     pv.product_id)
 JOIN public.seller_profiles sp ON sp.user_id=sps.seller_id
 JOIN public.profiles pr ON pr.id=sp.user_id
 JOIN public.whatsapp_contact_consents cc
   ON cc.phone_e164=private.ff_whatsapp_e164(sp.phone)
  AND cc.purpose='transactional' AND cc.status='opted_in'
  AND cc.consented_at IS NOT NULL AND cc.revoked_at IS NULL
 JOIN public.products prod ON prod.id=sps.approved_product_id AND prod.is_active IS TRUE
 WHERE sps.approved_product_id IS NOT NULL
   AND sp.status='active' AND sp.phone_verified_at IS NOT NULL
   AND pr.phone_verified_at IS NOT NULL
   AND private.ff_whatsapp_e164(pr.phone)=private.ff_whatsapp_e164(sp.phone)
   AND private.ff_whatsapp_e164(sp.phone) IS NOT NULL
 ON CONFLICT(order_id,seller_id,event_type) DO NOTHING;

 GET DIAGNOSTICS v_inserted=ROW_COUNT;
 RETURN v_inserted;
END;
$function$;
REVOKE ALL ON FUNCTION public.stage_whatsapp_seller_order_alert(bigint,timestamptz)
 FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.stage_whatsapp_seller_order_alert(bigint,timestamptz)
 TO service_role;
COMMENT ON TABLE public.whatsapp_seller_order_notification_outbox IS
 'Private, deduplicated seller transactional alerts. Only canonical approved product ownership routes orders; only verified, explicitly opted-in sellers qualify.';
