create or replace function public.crm_log_b2b_deal_stage()
returns trigger language plpgsql security definer set search_path=pg_catalog,public,auth
as $$
begin
 if tg_op='INSERT' then
   insert into public.crm_b2b_deal_stage_history(deal_id,from_stage,to_stage,changed_by) values(new.id,null,new.stage,auth.uid());
 elsif old.stage is distinct from new.stage then
   insert into public.crm_b2b_deal_stage_history(deal_id,from_stage,to_stage,changed_by) values(new.id,old.stage,new.stage,auth.uid());
 end if;
 return new;
end $$;
drop trigger if exists crm_b2b_deal_stage_audit on public.crm_b2b_deals;
create trigger crm_b2b_deal_stage_audit after insert or update of stage on public.crm_b2b_deals for each row execute function public.crm_log_b2b_deal_stage();

create or replace function public.crm_sales_metrics()
returns jsonb language plpgsql stable security definer set search_path=pg_catalog,public,auth
as $$
declare result jsonb;
begin
 if not public.crm_has_role(array['sales']) then raise exception 'Sales access required' using errcode='42501'; end if;
 select jsonb_build_object(
  'open_deals',count(*) filter(where d.stage not in ('fulfilled','lost')),
  'pipeline_value',coalesce(sum(d.estimated_value) filter(where d.stage not in ('fulfilled','lost')),0),
  'fulfilled_revenue',coalesce(sum(d.estimated_value) filter(where d.stage='fulfilled' and d.updated_at>=date_trunc('month',now())),0),
  'avg_days_to_fulfill', (select round(avg(extract(epoch from (h.changed_at-d.created_at))/86400)::numeric,1)
    from public.crm_b2b_deal_stage_history h join public.crm_b2b_deals d on d.id=h.deal_id
    where h.to_stage='fulfilled' and h.changed_at>=date_trunc('month',now())),
  'quota_target',coalesce((select sum(q.revenue_target) from public.crm_sales_quotas q where q.user_id=(select auth.uid()) and current_date between q.period_start and q.period_end),0),
  'my_fulfilled_revenue',coalesce((select sum(d.estimated_value) from public.crm_b2b_deals d where d.owner_user_id=(select auth.uid()) and d.stage='fulfilled' and d.updated_at>=date_trunc('month',now())),0)
 ) into result from public.crm_b2b_deals d;
 return result;
end $$;
revoke all on function public.crm_sales_metrics() from public,anon;
grant execute on function public.crm_sales_metrics() to authenticated;

create or replace function public.crm_support_metrics()
returns jsonb language plpgsql stable security definer set search_path=pg_catalog,public,auth
as $$
declare v_role text; v_channel text; result jsonb;
begin
 select m.role into v_role from public.crm_team_members m where m.user_id=(select auth.uid()) and m.is_active is true
 and m.role in ('customer_support','seller_support');
 if v_role is null then raise exception 'Support access required' using errcode='42501'; end if;
 v_channel:=case when v_role='customer_support' then 'customer_support' else 'seller_support' end;
 select jsonb_build_object(
  'open_tickets',count(*) filter(where t.status not in ('closed')),
  'overdue_tickets',count(*) filter(where t.status not in ('closed') and t.sla_due_at is not null and t.sla_due_at<now()),
  'avg_first_response_minutes', (select round(avg(extract(epoch from (m.first_reply-t.created_at))/60)::numeric,1)
    from public.support_tickets t
    cross join lateral (select min(sm.created_at) first_reply from public.support_ticket_messages sm where sm.ticket_id=t.id and sm.sender_role in ('admin','customer_care') and sm.created_at>=t.created_at) m
    where t.channel=v_channel and m.first_reply is not null),
  'first_contact_resolution_pct',coalesce(100.0*count(*) filter(where t.status='closed' and (select count(*) from public.support_ticket_messages sm where sm.ticket_id=t.id and sm.sender_role in ('admin','customer_care'))<=1)/nullif(count(*) filter(where t.status='closed'),0),0)
 ) into result from public.support_tickets t where t.channel=v_channel;
 return result;
end $$;
revoke all on function public.crm_support_metrics() from public,anon;
grant execute on function public.crm_support_metrics() to authenticated;

