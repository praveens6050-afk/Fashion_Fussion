 created_by uuid references auth.users(id) on delete set null, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.crm_b2b_quotes (
 id bigint generated by default as identity primary key, deal_id bigint not null references public.crm_b2b_deals(id) on delete cascade,
 quote_number text not null unique, subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
 discount_amount numeric(12,2) not null default 0 check (discount_amount >= 0), freight_estimate numeric(12,2) not null default 0 check (freight_estimate >= 0),
 tax_estimate numeric(12,2) not null default 0 check (tax_estimate >= 0), currency text not null default 'INR',
