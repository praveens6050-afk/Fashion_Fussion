-- Branch/staging only. No automatic dispatch, live sends or scheduler.
CREATE TABLE IF NOT EXISTS public.whatsapp_admin_alert_recipients (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 phone_e164 text NOT NULL CHECK (phone_e164 ~ '^\+[1-9][0-9]{7,14}$'),
 verified_at timestamptz,
 enabled boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(user_id, phone_e164)
);
CREATE INDEX IF NOT EXISTS whatsapp_admin_alert_recipients_active_idx ON public.whatsapp_admin_alert_recipients(user_id) WHERE enabled AND verified_at IS NOT NULL;
CREATE TABLE IF NOT EXISTS public.whatsapp_admin_alert_outbox (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recipient_id bigint NOT NULL REFERENCES public.whatsapp_admin_alert_recipients(id) ON DELETE RESTRICT,
 event_key text NOT NULL CHECK (length(event_key) BETWEEN 8 AND 160 AND event_key ~ '^[A-Za-z0-9._:-]+$'),
 alert_type text NOT NULL CHECK (alert_type IN ('order_attention','payment_attention','support_escalation','seller_review')),
 reference_code text NOT NULL CHECK (length(reference_code) BETWEEN 1 AND 80 AND reference_code !~ '[\\r\\n]'),
 status text NOT NULL DEFAULT 'pending_review' CHECK (status IN ('pending_review','ready','sending','accepted','delivered','read','failed','blocked')),
 attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count BETWEEN 0 AND 1),
 provider_message_id text CHECK (provider_message_id IS NULL OR (length(provider_message_id)<=255 AND provider_message_id ~ '^wamid[.][^[:space:]]+$')),
 last_error_code text CHECK (last_error_code IS NULL OR last_error_code ~ '^[A-Z0-9_:-]{1,64}$'),
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 attempt_started_at timestamptz, provider_sent_at timestamptz, provider_delivered_at timestamptz, provider_failed_at timestamptz,
 UNIQUE(recipient_id,event_key)
);
CREATE INDEX IF NOT EXISTS whatsapp_admin_alert_outbox_recent_idx ON public.whatsapp_admin_alert_outbox(created_at DESC,status);
ALTER TABLE public.whatsapp_admin_alert_recipients ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.whatsapp_admin_alert_outbox ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.whatsapp_admin_alert_recipients FROM PUBLIC,anon,authenticated;
REVOKE ALL ON TABLE public.whatsapp_admin_alert_outbox FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE public.whatsapp_admin_alert_recipients TO service_role;
GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE public.whatsapp_admin_alert_outbox TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.whatsapp_admin_alert_recipients_id_seq TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.whatsapp_admin_alert_outbox_id_seq TO service_role;
COMMENT ON TABLE public.whatsapp_admin_alert_recipients IS 'Server-managed verified admin WhatsApp allowlist. Never expose phone numbers to browser roles.';
COMMENT ON TABLE public.whatsapp_admin_alert_outbox IS 'Deduplicated admin alert delivery ledger. Contains references only, never customer PII or message payloads.';


-- Stage an alert only for currently verified, enabled admin recipients.
-- Does not claim an outbox row or send a message.
CREATE OR REPLACE FUNCTION public.stage_whatsapp_admin_alert(
  p_event_key text,
  p_alert_type text,
  p_reference_code text
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_inserted integer;
BEGIN
  IF p_event_key IS NULL OR length(p_event_key) NOT BETWEEN 8 AND 160
     OR p_event_key !~ '^[A-Za-z0-9._:-]+$'
     OR p_alert_type NOT IN ('order_attention','payment_attention','support_escalation','seller_review')
     OR p_reference_code IS NULL OR length(p_reference_code) NOT BETWEEN 1 AND 80
     OR p_reference_code ~ '[[:cntrl:]]'
  THEN
    RETURN 0;
  END IF;

  INSERT INTO public.whatsapp_admin_alert_outbox
    (recipient_id,event_key,alert_type,reference_code,status)
  SELECT r.id,p_event_key,p_alert_type,p_reference_code,'pending_review'
  FROM public.whatsapp_admin_alert_recipients r
  JOIN public.profiles p ON p.id=r.user_id AND p.is_admin IS TRUE
  WHERE r.enabled IS TRUE AND r.verified_at IS NOT NULL
    AND p.phone_verified_at IS NOT NULL
    AND private.ff_whatsapp_e164(p.phone) = r.phone_e164
  ON CONFLICT (recipient_id,event_key) DO NOTHING;

  GET DIAGNOSTICS v_inserted = ROW_COUNT;
  RETURN v_inserted;
END;
$function$;

REVOKE ALL ON FUNCTION public.stage_whatsapp_admin_alert(text,text,text)
  FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.stage_whatsapp_admin_alert(text,text,text)
  TO service_role;


-- Atomic at-most-once claim for the future private admin dispatcher.
CREATE OR REPLACE FUNCTION public.claim_whatsapp_admin_alert(
 p_outbox_id bigint,
 p_activation_cutoff timestamptz
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE v_claim record;
BEGIN
 IF p_outbox_id IS NULL OR p_outbox_id<=0 OR p_activation_cutoff IS NULL
    OR p_activation_cutoff>now() OR p_activation_cutoff<'2026-10-01'::timestamptz
 THEN RETURN NULL; END IF;

 PERFORM pg_catalog.pg_advisory_xact_lock(733013,417021);
 IF (SELECT count(*) FROM public.whatsapp_admin_alert_outbox
      WHERE attempt_started_at>=now()-interval '1 hour')>=5
    OR (SELECT count(*) FROM public.whatsapp_admin_alert_outbox
      WHERE attempt_started_at>=now()-interval '24 hours')>=20
 THEN RETURN NULL; END IF;

 UPDATE public.whatsapp_admin_alert_outbox ob
 SET status='sending',attempt_count=1,attempt_started_at=now(),updated_at=now()
 FROM public.whatsapp_admin_alert_recipients r
 JOIN public.profiles p ON p.id=r.user_id AND p.is_admin IS TRUE
 WHERE ob.id=p_outbox_id AND ob.recipient_id=r.id
   AND ob.status='ready' AND ob.attempt_count=0
   AND ob.provider_message_id IS NULL AND ob.attempt_started_at IS NULL
   AND ob.created_at>=greatest(p_activation_cutoff,now()-interval '24 hours')
   AND ob.created_at<=now()
   AND r.enabled IS TRUE AND r.verified_at IS NOT NULL
   AND p.phone_verified_at IS NOT NULL
   AND private.ff_whatsapp_e164(p.phone)=r.phone_e164
 RETURNING ob.id,r.phone_e164,ob.alert_type,ob.reference_code
 INTO v_claim;
 IF NOT FOUND THEN RETURN NULL; END IF;

 RETURN pg_catalog.jsonb_build_object(
   'outboxId',v_claim.id,'recipientPhone',v_claim.phone_e164,
   'alertType',v_claim.alert_type,'referenceCode',v_claim.reference_code
 );
END;
$function$;
REVOKE ALL ON FUNCTION public.claim_whatsapp_admin_alert(bigint,timestamptz)
 FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.claim_whatsapp_admin_alert(bigint,timestamptz)
 TO service_role;

CREATE OR REPLACE FUNCTION public.finish_whatsapp_admin_alert(
 p_outbox_id bigint,
 p_provider_message_id text,
 p_error_code text DEFAULT NULL
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE v_changed integer;
BEGIN
 IF p_outbox_id IS NULL OR p_outbox_id<=0
    OR length(coalesce(p_error_code,''))>64
    OR (p_error_code IS NOT NULL AND p_error_code !~ '^[A-Z0-9_:-]{1,64}$')
    OR (p_provider_message_id IS NOT NULL AND
      (length(p_provider_message_id)>255 OR p_provider_message_id !~ '^wamid[.][^[:space:]]+$'))
 THEN RETURN false; END IF;

 UPDATE public.whatsapp_admin_alert_outbox
 SET status=CASE WHEN p_provider_message_id IS NOT NULL THEN 'accepted'
                 WHEN p_error_code='PROVIDER_OUTCOME_UNKNOWN' THEN 'blocked'
                 ELSE 'failed' END,
     provider_message_id=p_provider_message_id,last_error_code=p_error_code,updated_at=now()
 WHERE id=p_outbox_id AND status='sending' AND attempt_count=1
   AND provider_message_id IS NULL;
 GET DIAGNOSTICS v_changed=ROW_COUNT;
 RETURN v_changed=1;
END;
$function$;
REVOKE ALL ON FUNCTION public.finish_whatsapp_admin_alert(bigint,text,text)
 FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.finish_whatsapp_admin_alert(bigint,text,text)
 TO service_role;
