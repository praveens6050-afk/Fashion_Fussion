create table if not exists public.seller_leads (
  id bigint generated by default as identity primary key,
  company_name text not null,
  source_marketplace text not null,
  source_url text,
  category text,
  city text,
  state text,
  business_type text,
  gstin text,
  public_contact_name text,
  contact_method text not null default 'platform_inquiry',
  lead_status text not null default 'new' check (lead_status in ('new','shortlisted','contacted','interested','onboarding','converted','not_interested','invalid')),
  priority text not null default 'medium' check (priority in ('high','medium','low')),
  notes text,
  source_checked_at timestamptz not null default now(),
  contacted_at timestamptz,
  converted_seller_id uuid references public.seller_profiles(user_id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_name, source_marketplace)
);

create index if not exists seller_leads_status_idx on public.seller_leads(lead_status);
create index if not exists seller_leads_category_idx on public.seller_leads(category);
create index if not exists seller_leads_location_idx on public.seller_leads(state, city);

alter table public.seller_leads enable row level security;

revoke all on table public.seller_leads from anon, authenticated;
grant select, insert, update, delete on table public.seller_leads to authenticated;
grant usage, select on sequence public.seller_leads_id_seq to authenticated;

create policy "seller_leads_admin_select"
on public.seller_leads for select
to authenticated
using (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.is_admin is true));

create policy "seller_leads_admin_insert"
on public.seller_leads for insert
to authenticated
with check (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.is_admin is true));

create policy "seller_leads_admin_update"
on public.seller_leads for update
to authenticated
using (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.is_admin is true))
with check (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.is_admin is true));

create policy "seller_leads_admin_delete"
on public.seller_leads for delete
to authenticated
using (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.is_admin is true));
