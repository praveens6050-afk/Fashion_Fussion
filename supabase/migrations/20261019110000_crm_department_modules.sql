-- CRM department module schema. Branch-only; not applied to production.
create table if not exists public.crm_b2b_accounts (
 id bigint generated by default as identity primary key,
 parent_account_id bigint references public.crm_b2b_accounts(id) on delete set null,
 company_name text not null, billing_email text, billing_address jsonb not null default '{}'::jsonb,
 gstin text, credit_limit numeric(12,2) not null default 0 check (credit_limit >= 0),
 account_status text not null default 'prospect' check (account_status in ('prospect','active','on_hold','closed')),
 owner_user_id uuid references auth.users(id) on delete set null, notes text,
 created_by uuid references auth.users(id) on delete set null, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.crm_b2b_deals (
 id bigint generated by default as identity primary key, account_id bigint not null references public.crm_b2b_accounts(id) on delete cascade,
 title text not null, stage text not null default 'inquiry_received' check (stage in ('inquiry_received','requirements_confirmed','quote_sent','sample_dispatched','negotiation','invoice_paid','fulfilled','lost')),
 estimated_value numeric(12,2) not null default 0 check (estimated_value >= 0), expected_close_date date,
 owner_user_id uuid references auth.users(id) on delete set null, next_action text, next_action_at timestamptz, lost_reason text,
 created_by uuid references auth.users(id) on delete set null, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.crm_b2b_quotes (
 id bigint generated by default as identity primary key, deal_id bigint not null references public.crm_b2b_deals(id) on delete cascade,
 quote_number text not null unique, subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
 discount_amount numeric(12,2) not null default 0 check (discount_amount >= 0), freight_estimate numeric(12,2) not null default 0 check (freight_estimate >= 0),
 tax_estimate numeric(12,2) not null default 0 check (tax_estimate >= 0), currency text not null default 'INR',
 valid_until date, status text not null default 'draft' check (status in ('draft','sent','accepted','expired','rejected')),
 terms text, created_by uuid references auth.users(id) on delete set null, created_at timestamptz not null default now()
);
create table if not exists public.crm_sales_activities (
 id bigint generated by default as identity primary key, account_id bigint references public.crm_b2b_accounts(id) on delete cascade,
 deal_id bigint references public.crm_b2b_deals(id) on delete cascade,
 activity_type text not null check (activity_type in ('call','email_log','meeting','sample','note','follow_up')),
 summary text not null, outcome text, follow_up_at timestamptz,
 created_by uuid references auth.users(id) on delete set null, created_at timestamptz not null default now()
);
create table if not exists public.crm_support_macros (
 id bigint generated by default as identity primary key,
 department text not null check (department in ('customer_support','seller_support')),
 title text not null, response_text text not null, is_active boolean not null default true,
 created_by uuid references auth.users(id) on delete set null, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.crm_marketing_campaigns (
 id bigint generated by default as identity primary key, name text not null,
 channel text not null check (channel in ('email','whatsapp','sms','facebook','instagram','onsite')),
 objective text not null default 'retention', audience_rule jsonb not null default '{}'::jsonb,
 journey_definition jsonb not null default '[]'::jsonb,
 status text not null default 'draft' check (status in ('draft','planned','paused','completed')),
 starts_at timestamptz, ends_at timestamptz, budget numeric(12,2) not null default 0 check (budget >= 0),
 notes text, created_by uuid references auth.users(id) on delete set null, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.crm_rfm_segments (
 id bigint generated by default as identity primary key, customer_id uuid not null unique references auth.users(id) on delete cascade,
 recency_days integer, order_frequency integer not null default 0, monetary_value numeric(12,2) not null default 0,
 segment text not null, calculated_at timestamptz not null default now()
);
create table if not exists public.crm_ab_tests (
 id bigint generated by default as identity primary key, name text not null, surface text not null,
 variant_a text not null, variant_b text not null, hypothesis text,
 starts_at timestamptz, ends_at timestamptz, impressions_a bigint not null default 0 check (impressions_a >= 0),
 conversions_a bigint not null default 0 check (conversions_a >= 0), impressions_b bigint not null default 0 check (impressions_b >= 0),
 conversions_b bigint not null default 0 check (conversions_b >= 0),
 status text not null default 'draft' check (status in ('draft','running','completed')),
 created_by uuid references auth.users(id) on delete set null, created_at timestamptz not null default now()
);
