-- Secure CRM email intake bridge for authenticated Zoho Mail forwarding/workflows.
-- This stages incoming messages only; no outbound email is sent.
BEGIN;

CREATE TABLE IF NOT EXISTS public.crm_email_inbound_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider text NOT NULL DEFAULT 'zoho_mail' CHECK (provider IN ('zoho_mail')),
  external_message_id text NOT NULL CHECK (length(external_message_id) BETWEEN 1 AND 255),
  sender_email text NOT NULL CHECK (length(sender_email) BETWEEN 3 AND 254),
  recipient_email text NOT NULL CHECK (length(recipient_email) BETWEEN 3 AND 254),
  subject text NOT NULL DEFAULT '' CHECK (length(subject)<=500),
  message_text text NOT NULL DEFAULT '' CHECK (length(message_text)<=20000),
  support_team text NOT NULL CHECK (support_team IN ('customer_support','seller_support','sales_marketing','admin_operations')),
  routing_status text NOT NULL DEFAULT 'needs_review' CHECK (routing_status IN ('needs_review','classified','closed')),
  received_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(provider,external_message_id)
);
CREATE INDEX IF NOT EXISTS crm_email_inbound_queue_idx
  ON public.crm_email_inbound_events(support_team,routing_status,received_at DESC);
ALTER TABLE public.crm_email_inbound_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.crm_email_inbound_events FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE public.crm_email_inbound_events TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.crm_email_inbound_events_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.ingest_crm_email_message(
 p_external_message_id text,
 p_sender_email text,
 p_recipient_email text,
 p_subject text,
 p_message_text text,
 p_received_at timestamptz
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
 v_role text := coalesce(auth.role(),'');
 v_sender text := lower(btrim(coalesce(p_sender_email,'')));
 v_recipient text := lower(btrim(coalesce(p_recipient_email,'')));
 v_team text;
 v_id bigint;
 v_inserted boolean := false;
BEGIN
 IF v_role <> 'service_role' THEN
   RAISE EXCEPTION 'Server integration access required' USING errcode='42501';
 END IF;
 IF p_external_message_id IS NULL OR length(p_external_message_id) NOT BETWEEN 1 AND 255
    OR v_sender !~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'
    OR v_recipient !~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'
    OR length(coalesce(p_subject,''))>500
    OR length(coalesce(p_message_text,''))>20000
    OR p_received_at IS NULL OR p_received_at > now()+interval '5 minutes'
    OR p_received_at < now()-interval '90 days'
 THEN RAISE EXCEPTION 'Invalid email event' USING errcode='22023'; END IF;
 v_team := CASE v_recipient
   WHEN 'customer.care@fashionfussion.in' THEN 'customer_support'
   WHEN 'seller.support@fashionfussion.in' THEN 'seller_support'
   WHEN 'sales.team@fashionfussion.in' THEN 'sales_marketing'
   WHEN 'orders@fashionfussion.in' THEN 'admin_operations'
   ELSE NULL
 END;
 IF v_team IS NULL THEN RAISE EXCEPTION 'Recipient mailbox is not an approved CRM route' USING errcode='42501'; END IF;
 INSERT INTO public.crm_email_inbound_events
   (external_message_id,sender_email,recipient_email,subject,message_text,support_team,received_at)
 VALUES (p_external_message_id,v_sender,v_recipient,coalesce(p_subject,''),coalesce(p_message_text,''),v_team,p_received_at)
 ON CONFLICT(provider,external_message_id) DO NOTHING
 RETURNING id INTO v_id;
 v_inserted := v_id IS NOT NULL;
 IF v_id IS NULL THEN
   SELECT id INTO v_id FROM public.crm_email_inbound_events
    WHERE provider='zoho_mail' AND external_message_id=p_external_message_id;
 END IF;
 RETURN jsonb_build_object('accepted',v_id IS NOT NULL,'inserted',v_inserted,'eventId',v_id,
   'team',v_team,'status','needs_review','message','Email staged in CRM; no outbound email sent.');
END;
$function$;
REVOKE ALL ON FUNCTION public.ingest_crm_email_message(text,text,text,text,text,timestamptz) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.ingest_crm_email_message(text,text,text,text,text,timestamptz) TO service_role;

CREATE OR REPLACE FUNCTION public.admin_crm_email_support_snapshot()
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE v_team text; v_uid uuid := auth.uid(); v_admin boolean := false;
BEGIN
 IF v_uid IS NULL THEN RAISE EXCEPTION 'Authentication required' USING errcode='28000'; END IF;
 SELECT coalesce(p.is_admin,false) INTO v_admin FROM public.profiles p WHERE p.id=v_uid;
 v_team := public.crm_whatsapp_actor_team();
 RETURN jsonb_build_object(
  'actor_team',v_team,'is_admin',coalesce(v_admin,false),'generated_at',now(),
  'recent',coalesce((SELECT jsonb_agg(to_jsonb(t) ORDER BY t.received_at DESC)
   FROM (SELECT e.id,e.sender_email,e.recipient_email,e.subject,e.message_text,e.support_team,e.routing_status,e.received_at,
       (SELECT r.id FROM public.crm_email_reply_outbox r WHERE r.inbound_event_id=e.id ORDER BY r.created_at DESC LIMIT 1) AS latest_reply_id,
       (SELECT r.status FROM public.crm_email_reply_outbox r WHERE r.inbound_event_id=e.id ORDER BY r.created_at DESC LIMIT 1) AS latest_reply_status
     FROM public.crm_email_inbound_events e
     WHERE (v_admin OR e.support_team=v_team)
     ORDER BY e.received_at DESC LIMIT 100) t),'[]'::jsonb),
  'queues',jsonb_build_object(
   'customer_support',(SELECT count(*) FROM public.crm_email_inbound_events WHERE support_team='customer_support' AND (v_admin OR support_team=v_team)),
   'seller_support',(SELECT count(*) FROM public.crm_email_inbound_events WHERE support_team='seller_support' AND (v_admin OR support_team=v_team)),
   'sales_marketing',(SELECT count(*) FROM public.crm_email_inbound_events WHERE support_team='sales_marketing' AND (v_admin OR support_team=v_team)),
   'admin_operations',(SELECT count(*) FROM public.crm_email_inbound_events WHERE support_team='admin_operations' AND (v_admin OR support_team=v_team))
  )
 );
END;
$function$;
REVOKE ALL ON FUNCTION public.admin_crm_email_support_snapshot() FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.admin_crm_email_support_snapshot() TO authenticated;
COMMIT;
