-- Fashion Fussion AI agent control plane.
-- Adds a server-only run ledger and approval queue. Does not enable any
-- external messaging, payments, refunds, payouts, advertising or publishing.

create table if not exists public.ai_agent_registry (
  agent_id text primary key check (agent_id ~ '^[a-z][a-z0-9_]{2,63}$'),
  display_name text not null,
  description text not null default '',
  enabled boolean not null default false,
  execution_mode text not null default 'assist'
    check (execution_mode in ('assist','draft_only','automatic')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ai_agent_runs (
  id uuid primary key default gen_random_uuid(),
  agent_id text not null references public.ai_agent_registry(agent_id) on delete restrict,
  action text not null check (length(action) between 2 and 80),
  status text not null default 'queued'
    check (status in ('queued','running','awaiting_approval','succeeded','failed','cancelled')),
  idempotency_key text not null check (idempotency_key ~ '^[A-Za-z0-9._:-]{8,160}$'),
  requested_by uuid references auth.users(id) on delete set null,
  source text not null default 'api' check (length(source) <= 80),
  input jsonb not null default '{}'::jsonb check (pg_column_size(input) <= 32768),
  output jsonb,
  error_code text check (error_code is null or error_code ~ '^[A-Za-z0-9_:-]{1,80}$'),
  started_at timestamptz,
  finished_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (agent_id, idempotency_key)
);

create index if not exists ai_agent_runs_status_created_idx
  on public.ai_agent_runs(status, created_at desc);
create index if not exists ai_agent_runs_agent_created_idx
  on public.ai_agent_runs(agent_id, created_at desc);

create table if not exists public.ai_agent_events (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.ai_agent_runs(id) on delete cascade,
  event_type text not null check (length(event_type) between 2 and 80),
  detail jsonb not null default '{}'::jsonb check (pg_column_size(detail) <= 16384),
  created_at timestamptz not null default now()
);
create index if not exists ai_agent_events_run_created_idx
  on public.ai_agent_events(run_id, created_at);

create table if not exists public.ai_agent_approvals (
  id uuid primary key default gen_random_uuid(),
  run_id uuid not null references public.ai_agent_runs(id) on delete cascade,
  action_key text not null check (length(action_key) between 2 and 80),
  status text not null default 'pending'
    check (status in ('pending','approved','rejected','expired')),
  requested_by uuid references auth.users(id) on delete set null,
  reviewed_by uuid references auth.users(id) on delete set null,
  review_note text check (review_note is null or length(review_note) <= 2000),
  expires_at timestamptz not null default (now() + interval '48 hours'),
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (run_id, action_key)
);
create index if not exists ai_agent_approvals_pending_idx
  on public.ai_agent_approvals(status, created_at desc);

