create table if not exists public.seller_finance_status_events (
  id bigint generated by default as identity primary key,
  seller_id uuid not null references public.seller_profiles(user_id) on delete cascade,
  old_status text not null,
  new_status text not null check (new_status = 'pending_review'),
  note text not null check (nullif(trim(note), '') is not null),
  actor_id uuid not null references public.profiles(id),
  created_at timestamptz not null default now()
);

alter table public.seller_finance_status_events enable row level security;
revoke all on public.seller_finance_status_events from public, anon, authenticated;

create or replace function public.admin_mark_seller_kyc_under_review(
  p_seller_id uuid,
  p_note text
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_uid uuid := auth.uid();
  v_note text := nullif(trim(coalesce(p_note, '')), '');
  v_old_status text;
  v_now timestamptz := now();
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  if not exists (select 1 from public.profiles p where p.id = v_uid and p.is_admin = true) then
    raise exception 'Administrator access required';
  end if;
  if v_note is null or length(v_note) > 500 then raise exception 'An internal note of 1 to 500 characters is required'; end if;

  select c.verification_status into v_old_status
  from public.seller_compliance_profiles c
  where c.seller_id = p_seller_id
  for update;
  if not found then raise exception 'Seller KYC profile not found'; end if;
  if v_old_status <> 'draft' then raise exception 'Only Draft KYC can be moved to Under Verification'; end if;

  update public.seller_compliance_profiles
  set verification_status = 'pending_review', updated_at = v_now
  where seller_id = p_seller_id;

  insert into public.seller_finance_status_events(seller_id, old_status, new_status, note, actor_id)
  values (p_seller_id, v_old_status, 'pending_review', v_note, v_uid);

  return jsonb_build_object('ok', true, 'seller_id', p_seller_id, 'old_status', v_old_status, 'new_status', 'pending_review', 'updated_at', v_now);
end;
$$;

revoke all on function public.admin_mark_seller_kyc_under_review(uuid, text) from public;
grant execute on function public.admin_mark_seller_kyc_under_review(uuid, text) to authenticated;
