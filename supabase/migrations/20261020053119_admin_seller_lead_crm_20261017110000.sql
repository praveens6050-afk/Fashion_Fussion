-- Fashion Fussion CRM: additive seller-lead contact, task and activity support.
-- This migration is intentionally committed to crm-development only; do not apply to production without approval.

alter table public.seller_leads
  add column if not exists public_contact_phone text,
  add column if not exists public_contact_email text,
  add column if not exists assigned_to uuid references public.profiles(id) on delete set null;

create table if not exists public.seller_lead_tasks (
  id bigint generated by default as identity primary key,
  lead_id bigint not null references public.seller_leads(id) on delete cascade,
  title text not null check (char_length(trim(title)) between 2 and 200),
  description text check (description is null or char_length(description) <= 4000),
  due_at timestamptz,
  task_status text not null default 'open' check (task_status in ('open','in_progress','completed','cancelled')),
  priority text not null default 'medium' check (priority in ('high','medium','low')),
  assigned_to uuid references public.profiles(id) on delete set null,
  created_by uuid references public.profiles(id) on delete set null,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((task_status = 'completed' and completed_at is not null) or (task_status <> 'completed'))
);

create index if not exists seller_lead_tasks_open_due_idx
  on public.seller_lead_tasks (due_at) where task_status in ('open','in_progress');
create index if not exists seller_lead_tasks_lead_idx
  on public.seller_lead_tasks (lead_id, created_at desc);

create table if not exists public.seller_lead_activities (
  id bigint generated by default as identity primary key,
  lead_id bigint not null references public.seller_leads(id) on delete cascade,
  activity_type text not null check (activity_type in ('created','updated','status_changed','contacted','note','task_created','task_completed','imported')),
  summary text not null check (char_length(trim(summary)) between 1 and 240),
  details text check (details is null or char_length(details) <= 4000),
  contact_channel text check (contact_channel is null or contact_channel in ('phone','email','whatsapp','instagram','website','other')),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists seller_lead_activities_lead_idx
  on public.seller_lead_activities (lead_id, created_at desc);

alter table public.seller_lead_tasks enable row level security;
alter table public.seller_lead_activities enable row level security;

