-- CRM-only WhatsApp support inbox and reviewed reply queue.
-- Replies are staged for review; this migration never calls Meta or sends messages.
BEGIN;

ALTER TABLE public.whatsapp_inbound_events
  ADD COLUMN IF NOT EXISTS support_team text NOT NULL DEFAULT 'sales_marketing';

UPDATE public.whatsapp_inbound_events
SET support_team = CASE sender_role
  WHEN 'customer' THEN 'customer_support'
  WHEN 'seller' THEN 'seller_support'
  WHEN 'admin' THEN 'admin_operations'
  ELSE 'sales_marketing'
END
WHERE support_team IS NULL OR support_team='sales_marketing';

DO $constraints$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_catalog.pg_constraint
    WHERE conrelid='public.whatsapp_inbound_events'::regclass
      AND conname='whatsapp_inbound_events_support_team_check'
  ) THEN
    ALTER TABLE public.whatsapp_inbound_events
      ADD CONSTRAINT whatsapp_inbound_events_support_team_check
      CHECK (support_team IN ('customer_support','seller_support','sales_marketing','admin_operations'));
  END IF;
END
$constraints$;

CREATE OR REPLACE FUNCTION public.set_whatsapp_inbound_support_team()
RETURNS trigger LANGUAGE plpgsql SET search_path = ''
AS $function$
BEGIN
  NEW.support_team := CASE NEW.sender_role
    WHEN 'customer' THEN 'customer_support'
    WHEN 'seller' THEN 'seller_support'
    WHEN 'admin' THEN 'admin_operations'
    ELSE 'sales_marketing'
  END;
  RETURN NEW;
END;
$function$;
REVOKE ALL ON FUNCTION public.set_whatsapp_inbound_support_team()
  FROM PUBLIC,anon,authenticated,service_role;
DROP TRIGGER IF EXISTS trg_whatsapp_inbound_support_team ON public.whatsapp_inbound_events;
CREATE TRIGGER trg_whatsapp_inbound_support_team
  BEFORE INSERT OR UPDATE OF sender_role,support_team ON public.whatsapp_inbound_events
  FOR EACH ROW EXECUTE FUNCTION public.set_whatsapp_inbound_support_team();

CREATE INDEX IF NOT EXISTS whatsapp_inbound_support_queue_idx
  ON public.whatsapp_inbound_events(support_team,routing_status,created_at DESC);

CREATE TABLE IF NOT EXISTS public.whatsapp_support_reply_outbox (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inbound_event_id bigint NOT NULL REFERENCES public.whatsapp_inbound_events(id) ON DELETE RESTRICT,
  request_key text NOT NULL UNIQUE CHECK (request_key ~ '^[A-Za-z0-9._:-]{8,160}$'),
  recipient_phone text NOT NULL CHECK (recipient_phone ~ '^[0-9]{8,15}$'),
  reply_text text NOT NULL CHECK (length(btrim(reply_text)) BETWEEN 1 AND 1000),
  requested_by uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'pending_review'
    CHECK (status IN ('pending_review','ready','sending','accepted','delivered','read','failed','blocked')),
  attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count BETWEEN 0 AND 1),
  provider_message_id text CHECK (provider_message_id IS NULL OR (length(provider_message_id)<=255 AND provider_message_id ~ '^wamid[.][^[:space:]]+$')),
  last_error_code text CHECK (last_error_code IS NULL OR last_error_code ~ '^[A-Z0-9_:-]{1,64}$'),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  attempt_started_at timestamptz,
  UNIQUE(inbound_event_id,request_key)
);
CREATE INDEX IF NOT EXISTS whatsapp_support_reply_recent_idx
  ON public.whatsapp_support_reply_outbox(status,created_at DESC);
ALTER TABLE public.whatsapp_support_reply_outbox ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.whatsapp_support_reply_outbox FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE public.whatsapp_support_reply_outbox TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.whatsapp_support_reply_outbox_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.admin_crm_whatsapp_support_snapshot()
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE v_uid uuid := auth.uid(); v_is_admin boolean := false;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'Authentication required' USING errcode='28000'; END IF;
  SELECT coalesce(p.is_admin,false) INTO v_is_admin FROM public.profiles p WHERE p.id=v_uid;
  IF NOT coalesce(v_is_admin,false) THEN RAISE EXCEPTION 'Administrator access required' USING errcode='42501'; END IF;
  RETURN jsonb_build_object(
    'generated_at',now(),
    'queues',jsonb_build_object(
      'customer_support',(SELECT count(*) FROM public.whatsapp_inbound_events WHERE support_team='customer_support'),
      'seller_support',(SELECT count(*) FROM public.whatsapp_inbound_events WHERE support_team='seller_support'),
      'sales_marketing',(SELECT count(*) FROM public.whatsapp_inbound_events WHERE support_team='sales_marketing'),
      'admin_operations',(SELECT count(*) FROM public.whatsapp_inbound_events WHERE support_team='admin_operations'),
      'needs_review',(SELECT count(*) FROM public.whatsapp_inbound_events WHERE routing_status='needs_review')
    ),
    'recent',coalesce((
      SELECT jsonb_agg(to_jsonb(t) ORDER BY t.created_at DESC)
      FROM (
        SELECT e.id,e.sender_phone,e.sender_role,e.routing_status,e.support_team,
               e.message_type,e.message_text,e.created_at,
               (SELECT r.status FROM public.whatsapp_support_reply_outbox r
                WHERE r.inbound_event_id=e.id ORDER BY r.created_at DESC LIMIT 1) AS latest_reply_status
        FROM public.whatsapp_inbound_events e
        ORDER BY e.created_at DESC LIMIT 100
      ) t
    ),'[]'::jsonb)
  );
END;
$function$;
REVOKE ALL ON FUNCTION public.admin_crm_whatsapp_support_snapshot() FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.admin_crm_whatsapp_support_snapshot() TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_crm_queue_whatsapp_reply(
 p_inbound_event_id bigint,p_reply_text text,p_request_key text
)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE v_uid uuid := auth.uid(); v_is_admin boolean := false; v_event public.whatsapp_inbound_events%rowtype; v_id bigint;
BEGIN
 IF v_uid IS NULL THEN RAISE EXCEPTION 'Authentication required' USING errcode='28000'; END IF;
 SELECT coalesce(p.is_admin,false) INTO v_is_admin FROM public.profiles p WHERE p.id=v_uid;
 IF NOT coalesce(v_is_admin,false) THEN RAISE EXCEPTION 'Administrator access required' USING errcode='42501'; END IF;
 IF p_inbound_event_id IS NULL OR p_inbound_event_id<=0
    OR p_reply_text IS NULL OR length(btrim(p_reply_text)) NOT BETWEEN 1 AND 1000
    OR p_request_key IS NULL OR p_request_key !~ '^[A-Za-z0-9._:-]{8,160}$'
 THEN RAISE EXCEPTION 'Invalid reply request' USING errcode='22023'; END IF;
 SELECT * INTO v_event FROM public.whatsapp_inbound_events WHERE id=p_inbound_event_id;
 IF NOT FOUND OR v_event.routing_status<>'classified' OR v_event.sender_role='unclassified'
 THEN RAISE EXCEPTION 'Sender requires identity review before replying' USING errcode='42501'; END IF;
 INSERT INTO public.whatsapp_support_reply_outbox
   (inbound_event_id,request_key,recipient_phone,reply_text,requested_by,status)
 VALUES (v_event.id,p_request_key,regexp_replace(v_event.sender_phone,'[^0-9]','','g'),btrim(p_reply_text),v_uid,'pending_review')
 ON CONFLICT (request_key) DO NOTHING
 RETURNING id INTO v_id;
 IF v_id IS NULL THEN
   SELECT id INTO v_id FROM public.whatsapp_support_reply_outbox WHERE request_key=p_request_key;
 END IF;
 RETURN jsonb_build_object('queued',v_id IS NOT NULL,'status','pending_review','replyId',v_id,
   'message','Reply queued for authorized review; no WhatsApp message was sent.');
END;
$function$;
REVOKE ALL ON FUNCTION public.admin_crm_queue_whatsapp_reply(bigint,text,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.admin_crm_queue_whatsapp_reply(bigint,text,text) TO authenticated;

COMMIT;
