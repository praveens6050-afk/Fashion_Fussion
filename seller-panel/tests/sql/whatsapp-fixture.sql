-- Isolated CI-only PostgreSQL fixture, never run against Fashion Fussion production.
-- This creates ONLY synthetic tables/users inside the ephemeral GitHub Actions DB.
CREATE SCHEMA IF NOT EXISTS auth;
CREATE SCHEMA IF NOT EXISTS private;
CREATE TABLE IF NOT EXISTS auth.users (
 id uuid PRIMARY KEY,
 email text NOT NULL,
 raw_user_meta_data jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE TABLE IF NOT EXISTS public.profiles (
 id uuid PRIMARY KEY REFERENCES auth.users(id),
 phone text,
 phone_verified_at timestamptz,
 is_admin boolean NOT NULL DEFAULT false
);
CREATE TABLE IF NOT EXISTS public.whatsapp_inbound_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 external_message_id text NOT NULL UNIQUE,
 sender_phone text NOT NULL,
 sender_role text NOT NULL DEFAULT 'unclassified' CHECK (sender_role IN ('admin','seller','customer','unclassified')),
 sender_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
 classification_source text NOT NULL DEFAULT 'none',
 routing_status text NOT NULL DEFAULT 'needs_review' CHECK (routing_status IN ('classified','needs_review')),
 message_type text,
 message_text text,
 phone_number_id text,
 business_phone text,
 meta_timestamp timestamptz,
 raw_message jsonb NOT NULL DEFAULT '{}'::jsonb,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.seller_profiles (
 user_id uuid PRIMARY KEY REFERENCES auth.users(id), phone text,
 phone_verified_at timestamptz, status text NOT NULL DEFAULT 'inactive'
);
CREATE TABLE IF NOT EXISTS public.products (
 id bigint PRIMARY KEY, is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS public.product_variants (
 id bigint PRIMARY KEY, product_id bigint NOT NULL REFERENCES public.products(id),
 is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS public.seller_product_submissions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 seller_id uuid NOT NULL REFERENCES auth.users(id),
 approved_product_id bigint REFERENCES public.products(id), status text NOT NULL DEFAULT 'pending'
);
DO $roles$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname='anon') THEN
    CREATE ROLE anon NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname='authenticated') THEN
    CREATE ROLE authenticated NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname='service_role') THEN
    CREATE ROLE service_role NOLOGIN;
  END IF;
END $roles$;
CREATE OR REPLACE FUNCTION auth.uid() RETURNS uuid
LANGUAGE sql STABLE SET search_path TO ''
AS $auth$
 SELECT NULLIF(pg_catalog.current_setting('ff.test_uid',true),'')::uuid
$auth$;

CREATE TABLE public.orders (
 id bigint PRIMARY KEY,
 user_id uuid,
 status text NOT NULL,
 fulfillment_status text NOT NULL DEFAULT 'ordered',
 payment_method text NOT NULL,
 payment_verified_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 fulfillment_updated_at timestamptz,
 customer_phone text,
 customer_name text,
 items jsonb NOT NULL DEFAULT '[]'::jsonb,
 display_order_id text
);

CREATE TABLE public.order_shipments (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL REFERENCES public.orders(id),
 direction text NOT NULL,
 awb_code text
);

CREATE TABLE public.whatsapp_order_consents (
 order_id bigint PRIMARY KEY REFERENCES public.orders(id),
 user_id uuid NOT NULL,
 phone_e164 text NOT NULL,
 source text NOT NULL DEFAULT 'checkout_checkbox',
 consented_at timestamptz NOT NULL,
 revoked_at timestamptz,
 updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.whatsapp_contact_consents (
 phone_e164 text NOT NULL,
 purpose text NOT NULL CHECK (purpose IN ('transactional','marketing')),
 status text NOT NULL CHECK (status IN ('opted_in','opted_out')),
 source text NOT NULL DEFAULT 'checkout_checkbox',
 proof_reference text NOT NULL DEFAULT 'synthetic-test',
 consented_at timestamptz,
 revoked_at timestamptz,
 updated_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY (phone_e164,purpose)
);

CREATE TABLE public.whatsapp_order_notification_outbox (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 order_id bigint NOT NULL REFERENCES public.orders(id),
 event_type text NOT NULL,
 status text NOT NULL DEFAULT 'pending_review',
 attempt_count integer NOT NULL DEFAULT 0,
 template_name text NOT NULL DEFAULT 'order_status_update',
 provider_message_id text,
 last_error_code text,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT whatsapp_order_notification_once_per_order_event UNIQUE(order_id,event_type)
);
